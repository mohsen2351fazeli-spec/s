const saveHnadler = () => {
  const stor = JSON.parse(localStorage.getItem("local")).duas;
  const ss = document.querySelectorAll(".ss");
  ss.forEach((s) => {
    s.addEventListener("click", () => {
      if (stor.includes(s.dataset.id)) {
        stor.splice(
          stor.findIndex((x) => {
            return x == s.dataset.id;
          }),
          1,
        );
        local.duas = stor;
        localStorage.setItem("local", JSON.stringify(local));
        ssHndler();
      } else {
        stor.push(s.dataset.id);
        local.duas = stor;
        localStorage.setItem("local", JSON.stringify(local));
        ssHndler();
      }
      sShow();
    });
  });
  ssHndler();
};
